                        <h5>Why is it necessary to replace the north bridge, replace the south bridge, replace the video
                            chip?</h5><img class="pull-right" src="assets/images/outsource/article-inner-1.jpg" alt="">
                        <p>For starters, you should explain what a chip is. BGA (Ball grid array) - this is the type of
                            the chassis (chip), the outputs of which are balls of solder, located on the reverse side of
                            the chip on the contact platform. This chip is installed on the motherboard using an
                            infrared soldering station.<br>As a rule, the laptop uses the following chips: north bridge,
                            south bridge, video chip. Each of these chips performs its specific functions and is
                            responsible for individual parts of the motherboard.<br><b>Southbridge</b> is a BGA chip
                            that provides communication between the motherboard and its components and functions as an
                            input and output concentrator. In other words, the south bridge functionally includes: an
                            SMBus bus controller, a PCI or PCI-Express controller, a DMA controller, a SATA , a power
                            management controller, a USB controller.</p>
                        <h5>Symptoms of a south bridge laptop</h5>
                        <ul class="list">
                            <li><span class="list-mark">1.</span>The laptop does not work USB ports, or part of the
                                ports.</li>
                            <li><span class="list-mark">2.</span>The keyboard does not work on the laptop.</li>
                            <li><span class="list-mark">3.</span>The hard disk is not detected in the laptop.</li>
                            <li><span class="list-mark">4.</span>The optical drive (CD, DVD) is not detected in the
                                laptop.</li>
                            <li><span class="list-mark">5.</span>The laptop turns on, but immediately goes to reboot.
                            </li>
                            <li><span class="list-mark">6.</span>The laptop does not turn on, the south bridge is
                                heated.</li>
                        </ul><img class="image" src="assets/images/outsource/article-inner-2.jpg" alt="">
                        <p><b>Northbridge</b> - provides connection of the motherboard to the processor, RAM and video
                            card. The chip in the BGA package, the north bridge, determines the frequency of the system
                            bus and the type of RAM. In budget notebooks, a video adapter (graphic core) is often
                            integrated into the north bridge.</p>
                        <h5>Symptoms of a failure of the north bridge of the laptop</h5>
                        <ul class="list">
                            <li><span class="list-mark">1.</span>The laptop then turns on, then there is no (blade of
                                the north bridge).</li>
                            <li><span class="list-mark">2.</span>The laptop turns on, but there is no image on the
                                screen (there is no initialization).</li>
                            <li><span class="list-mark">3.</span>The motherboard of the laptop does not see (does not
                                detect) the main memory, which is accompanied by short beeps of the speaker.</li>
                            <li><span class="list-mark">4.</span>Video adapter is not detected (there may be signs of
                                video adapter failure, video chip).</li>
                        </ul>
